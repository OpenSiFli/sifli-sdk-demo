int main(void)
{
    size_t index;

    for (index = 0U; index < sizeof(s_ui_glyphs) / sizeof(s_ui_glyphs[0]);
         ++index)
    {
        lv_font_glyph_dsc_t glyph;
        uint32_t codepoint = s_ui_glyphs[index];

        assert(device_ui_font.get_glyph_dsc(&device_ui_font, &glyph,
                                             codepoint, 0U));
        assert(glyph.box_w > 0U || codepoint == 0x20U);
        assert(lv_font_get_bitmap_fmt_txt(&device_ui_font, codepoint) != NULL ||
               codepoint == 0x20U);
    }

    return 0;
}
