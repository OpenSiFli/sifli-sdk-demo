"""Generate the host identity used for iPhone lockdown pairing
(root private key + root/host certificates).

Matches the behaviour of libimobiledevice's userpref.c:
  - root : RSA2048 self-signed, BasicConstraints = critical,CA:TRUE, empty subject/issuer
  - host : RSA2048, signed by the root key, BasicConstraints = critical,CA:FALSE,
           keyUsage = critical,digitalSignature,keyEncipherment
  - version v3, serial = 1, SHA256 signature, validity 2024-01-01 ~ 2044-01-01

The firmware only uses the root private key (to sign DeviceCertificate) and the
root/host certificates. The host private key is reserved for a future SSL
session (StartSession) and is not exported yet.

Usage:
    python gen_pair_identity.py      # run in this directory, writes iph_pair_identity.h
"""
import datetime
import os

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "iph_pair_identity.h")

NOT_BEFORE = datetime.datetime(2024, 1, 1)
NOT_AFTER = datetime.datetime(2044, 1, 1)

# Same format as a real host pairing record: 8 hex digits + '-' + 19 decimal digits / UUID
HOST_ID = "5AF01A2B-3C4D-4E5F-8A9B-0C1D2E3F4A5B"
SYSTEM_BUID = "A1B2C3D4-0000000000000000001"


def emit_array(name, data, per_line=12):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append('    ' + ', '.join('0x%02X' % b for b in chunk) + ',')
    return ('static const uint8_t %s[] __attribute__((unused)) = {\n%s\n};\n#define %s_LEN %uu\n'
            % (name, '\n'.join(lines), name.upper(), len(data)))


def make_root():
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    subject = x509.Name([])          # empty subject, same as a real host
    cert = (x509.CertificateBuilder()
            .subject_name(subject)
            .issuer_name(subject)
            .public_key(key.public_key())
            .serial_number(1)
            .not_valid_before(NOT_BEFORE)
            .not_valid_after(NOT_AFTER)
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .sign(key, hashes.SHA256()))
    return key, cert


def make_host(root_key, root_cert):
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    subject = x509.Name([])
    cert = (x509.CertificateBuilder()
            .subject_name(subject)
            .issuer_name(root_cert.subject)
            .public_key(key.public_key())
            .serial_number(1)
            .not_valid_before(NOT_BEFORE)
            .not_valid_after(NOT_AFTER)
            .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
            .add_extension(x509.KeyUsage(digital_signature=True,
                                         content_commitment=False,
                                         key_encipherment=True,
                                         data_encipherment=False,
                                         key_agreement=False,
                                         key_cert_sign=False,
                                         crl_sign=False,
                                         encipher_only=False,
                                         decipher_only=False), critical=True)
            .add_extension(x509.SubjectKeyIdentifier.from_public_key(key.public_key()),
                           critical=False)
            .sign(root_key, hashes.SHA256()))
    return key, cert


def main():
    root_key, root_cert = make_root()
    host_key, host_cert = make_host(root_key, root_cert)

    root_key_der = root_key.private_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PrivateFormat.TraditionalOpenSSL,   # PKCS#1 RSAPrivateKey
        encryption_algorithm=serialization.NoEncryption())
    root_cert_der = root_cert.public_bytes(serialization.Encoding.DER)
    host_cert_der = host_cert.public_bytes(serialization.Encoding.DER)

    out = []
    out.append('/*\n'
               ' * AUTO-GENERATED by gen_pair_identity.py -- do not edit by hand.\n'
               ' *\n'
               ' * Host identity used for iPhone lockdown pairing:\n'
               ' *   root private key (PKCS#1 DER) -- used by the firmware to sign DeviceCertificate\n'
               ' *   root certificate / host certificate (DER) -- placed in the PairRecord of the Pair request\n'
               ' * Structure follows libimobiledevice: empty subject, serial=1, SHA256,\n'
               ' * CA constraints as described in gen_pair_identity.py.\n'
               ' */\n')
    out.append('#ifndef IPH_PAIR_IDENTITY_H\n#define IPH_PAIR_IDENTITY_H\n\n#include <stdint.h>\n')
    out.append('#define IPH_HOST_ID     "%s"\n' % HOST_ID)
    out.append('#define IPH_SYSTEM_BUID "%s"\n\n' % SYSTEM_BUID)
    out.append(emit_array('iph_root_key_der', root_key_der))
    out.append(emit_array('iph_root_cert_der', root_cert_der))
    out.append(emit_array('iph_host_cert_der', host_cert_der))
    out.append('#endif /* IPH_PAIR_IDENTITY_H */\n')

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))

    print('wrote', os.path.normpath(OUT))
    print('HostID            ', HOST_ID)
    print('SystemBUID        ', SYSTEM_BUID)
    print('root key  (PKCS#1) %d bytes' % len(root_key_der))
    print('root cert          %d bytes' % len(root_cert_der))
    print('host cert          %d bytes' % len(host_cert_der))


if __name__ == '__main__':
    main()
